function seededRand(seed) {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return function () {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

function regenerateWindField() {
  const seed = parseInt(document.getElementById("wcSeedNum").value, 10) || 7;
  document.getElementById("wcSeedNumVal").textContent = seed;
  const rng = seededRand(seed * 9973 + 131);
  wcStems = [];
  for (let i = 0; i < 68; i++) {
    const xBase = 0.02 + Math.pow(rng(), 1.18) * 0.72;
    const h = 0.28 + rng() * 0.42 - (xBase > 0.52 ? 0.08 : 0);
    const isRicePanicle = (xBase > 0.32 && xBase < 0.76 && rng() > 0.34);
    const grains = isRicePanicle ? Math.floor(12 + rng() * 14) : 0;
    wcStems.push({
      xBase,
      h,
      isRicePanicle,
      grains,
      phase: rng() * Math.PI * 2,
      thickness: isRicePanicle ? (1.6 + rng() * 1.1) : (0.9 + rng() * 0.9),
      ghostOffset: 0.008 + rng() * 0.018
    });
  }
  renderWindCraft();
}

function randomizeWindStroke() {
  const r1 = 0.45 + Math.random() * 0.25;
  const r2 = 0.38 + Math.random() * 0.2;
  wcStrokePoints = [
    { x: 0.05, y: 0.65 + Math.random() * 0.2 },
    { x: 0.32, y: r1 },
    { x: 0.62, y: r2 },
    { x: 0.90, y: r2 - 0.06 + Math.random() * 0.1 }
  ];
  const sEl = document.getElementById("wcSeedNum");
  sEl.value = ((parseInt(sEl.value, 10) % 30) + 1);
  regenerateWindField();
}

function initWindCraft() {
  const canvas = document.getElementById("windCanvas");
  const getNormPos = (clientX, clientY) => {
    const rect = canvas.getBoundingClientRect();
    return {
      x: Math.max(0, Math.min(1, (clientX - rect.left) / rect.width)),
      y: Math.max(0, Math.min(1, (clientY - rect.top) / rect.height))
    };
  };

  canvas.addEventListener("mousedown", e => {
    wcDrawing = true;
    wcStrokePoints = [getNormPos(e.clientX, e.clientY)];
  });
  window.addEventListener("mousemove", e => {
    if (!wcDrawing) return;
    const p = getNormPos(e.clientX, e.clientY);
    const last = wcStrokePoints[wcStrokePoints.length - 1];
    if (Math.hypot(p.x - last.x, p.y - last.y) > 0.03) {
      wcStrokePoints.push(p);
      renderWindCraft();
    }
  });
  window.addEventListener("mouseup", () => {
    if (wcDrawing) {
      wcDrawing = false;
      renderWindCraft();
    }
  });

  canvas.addEventListener("touchstart", e => {
    if (e.touches.length === 1) {
      wcDrawing = true;
      wcStrokePoints = [getNormPos(e.touches[0].clientX, e.touches[0].clientY)];
    }
  }, { passive: true });
  canvas.addEventListener("touchmove", e => {
    if (wcDrawing && e.touches.length === 1) {
      e.preventDefault();
      const p = getNormPos(e.touches[0].clientX, e.touches[0].clientY);
      const last = wcStrokePoints[wcStrokePoints.length - 1];
      if (Math.hypot(p.x - last.x, p.y - last.y) > 0.03) {
        wcStrokePoints.push(p);
        renderWindCraft();
      }
    }
  }, { passive: false });
  canvas.addEventListener("touchend", () => { wcDrawing = false; renderWindCraft(); });

  regenerateWindField();
}

function drawWindArtwork(ctx, W, H) {
  const palette = document.getElementById("wcPalette").value;
  const windPower = parseInt(document.getElementById("wcWind").value, 10) / 100;
  const seedCount = parseInt(document.getElementById("wcSeeds").value, 10);
  const seedVal = parseInt(document.getElementById("wcSeedNum").value, 10) || 7;
  const rng = seededRand(seedVal * 4253 + 79);
  const scale = W / 1820;

  // Compute stroke wind vector
  let strokeDx = 0.65, strokeDy = -0.18;
  if (wcStrokePoints.length >= 2) {
    const first = wcStrokePoints[0];
    const last = wcStrokePoints[wcStrokePoints.length - 1];
    strokeDx = last.x - first.x;
    strokeDy = last.y - first.y;
    if (Math.abs(strokeDx) < 0.08) strokeDx = 0.45;
  }
  const bendDir = strokeDx >= 0 ? 1 : -1;

  // 1. Rich Printmaking Background
  const bgGrad = ctx.createLinearGradient(0, 0, W * 0.25, H);
  let mainInk, ghostInk, accentInk, ribbonInk;
  if (palette === "cyanotype") {
    bgGrad.addColorStop(0, "#0b2847");
    bgGrad.addColorStop(0.55, "#113a63");
    bgGrad.addColorStop(1, "#09213c");
    mainInk = "rgba(246, 252, 255, 0.94)";
    ghostInk = "rgba(135, 206, 242, 0.27)";
    accentInk = "rgba(215, 242, 255, 0.85)";
    ribbonInk = "rgba(165, 222, 250, 0.16)";
  } else if (palette === "morning") {
    bgGrad.addColorStop(0, "#f5efe1");
    bgGrad.addColorStop(0.45, "#ece3cf");
    bgGrad.addColorStop(1, "#dfd1b4");
    mainInk = "rgba(184, 132, 42, 0.92)";
    ghostInk = "rgba(107, 148, 134, 0.25)";
    accentInk = "rgba(44, 78, 86, 0.78)";
    ribbonInk = "rgba(82, 132, 138, 0.15)";
  } else {
    bgGrad.addColorStop(0, "#1c314a");
    bgGrad.addColorStop(0.48, "#515063");
    bgGrad.addColorStop(1, "#d99b5e");
    mainInk = "rgba(255, 249, 236, 0.93)";
    ghostInk = "rgba(255, 222, 173, 0.26)";
    accentInk = "rgba(255, 238, 198, 0.9)";
    ribbonInk = "rgba(255, 240, 215, 0.18)";
  }
  ctx.fillStyle = bgGrad;
  ctx.fillRect(0, 0, W, H);

  // 2. Subtle Washi Paper Fibers
  ctx.save();
  for (let i = 0; i < 420; i++) {
    const fx = rng() * W;
    const fy = rng() * H;
    const fl = (12 + rng() * 34) * scale;
    const fa = rng() * Math.PI;
    ctx.strokeStyle = palette === "morning" ? "rgba(120,98,68,0.055)" : "rgba(255,255,255,0.045)";
    ctx.lineWidth = (0.7 + rng() * 0.8) * scale;
    ctx.beginPath();
    ctx.moveTo(fx, fy);
    ctx.lineTo(fx + Math.cos(fa) * fl, fy + Math.sin(fa) * fl);
    ctx.stroke();
  }
  ctx.restore();

  // 3. Hand-Sculpted Wind Ribbons (respecting upper-right safe zone y < 0.34)
  ctx.save();
  for (let r = 0; r < 6; r++) {
    const yShift = (r - 2.5) * 0.045 * H;
    ctx.strokeStyle = ribbonInk;
    ctx.lineWidth = (2.2 + (r % 3) * 1.4) * scale;
    ctx.beginPath();
    const p0 = wcStrokePoints[0];
    const pLast = wcStrokePoints[wcStrokePoints.length - 1];
    const sy0 = Math.max(H * 0.37, p0.y * H + yShift);
    const sy1 = Math.max(H * 0.36, pLast.y * H + yShift * 0.7);
    ctx.moveTo(p0.x * W * 0.4, sy0);
    ctx.bezierCurveTo(
      W * 0.32, Math.max(H * 0.35, sy0 + strokeDy * H * 0.3),
      W * 0.58, Math.max(H * 0.36, sy1 - H * 0.05),
      Math.min(W * 0.85, Math.max(W * 0.65, pLast.x * W)), sy1
    );
    ctx.stroke();
  }
  ctx.restore();

  // 4. Botanical Stems & Heavy Rice Panicles (Ghost Wind Halo + Crisp Print)
  const drawStemPass = (isGhost) => {
    ctx.save();
    wcStems.forEach(st => {
      const bx = st.xBase * W;
      const by = H * 1.01;
      const extraGhost = isGhost ? st.ghostOffset * W * (0.8 + windPower) : 0;
      const bendX = bendDir * (st.h * W * (0.24 + windPower * 0.44)) + extraGhost;
      // Guarantee upper-right masthead safe zone remains 100% clear!
      const minTopY = (bx + bendX > W * 0.46) ? H * 0.35 : H * 0.14;
      const tipY = Math.max(minTopY, H - st.h * H * (1 - windPower * 0.22));
      const tipX = Math.min(W * 0.85, bx + bendX);
      const cpX = bx + bendX * 0.34;
      const cpY = H - (H - tipY) * 0.64;

      ctx.strokeStyle = isGhost ? ghostInk : (st.isRicePanicle ? mainInk : accentInk);
      ctx.lineWidth = st.thickness * scale * (isGhost ? 2.4 : 1.0);
      ctx.lineCap = "round";
      ctx.beginPath();
      ctx.moveTo(bx, by);
      ctx.quadraticCurveTo(cpX, cpY, tipX, tipY);
      ctx.stroke();

      if (st.isRicePanicle) {
        for (let g = 0; g < st.grains; g++) {
          const t = 0.48 + (g / st.grains) * 0.52;
          const gx = (1 - t) * (1 - t) * bx + 2 * (1 - t) * t * cpX + t * t * tipX;
          const gy = (1 - t) * (1 - t) * by + 2 * (1 - t) * t * cpY + t * t * tipY;
          const side = (g % 2 === 0 ? 1 : -1) * (5 + (1 - t) * 7) * scale;
          const droop = (g * 0.9) * scale * windPower;
          const angle = Math.atan2(tipY - cpY, tipX - cpX) + (g % 2 === 0 ? 0.35 : -0.35);

          ctx.save();
          ctx.translate(gx + bendDir * 3 * scale, gy + side + droop);
          ctx.rotate(angle);
          ctx.fillStyle = isGhost ? ghostInk : mainInk;
          ctx.beginPath();
          ctx.ellipse(0, 0, 7.2 * scale * (isGhost ? 1.35 : 1), 2.8 * scale * (isGhost ? 1.35 : 1), 0, 0, Math.PI * 2);
          ctx.fill();
          ctx.restore();
        }
      }
    });
    ctx.restore();
  };

  drawStemPass(true);
  drawStemPass(false);

  // 5. Drifting Wind-Borne Seeds / Glowing Husks on the Front Cover
  ctx.save();
  for (let s = 0; s < seedCount; s++) {
    const sx = W * (0.46 + rng() * 0.44);
    const sy = H * (0.36 + rng() * 0.46);
    // Keep vertical essay zone (x > 0.865, y in 0.30..0.63) clean
    if (sx > W * 0.855 && sy < H * 0.64) continue;
    const ang = -0.25 + rng() * 0.45;
    ctx.save();
    ctx.translate(sx, sy);
    ctx.rotate(ang);
    ctx.fillStyle = mainInk;
    ctx.beginPath();
    ctx.ellipse(0, 0, (4.5 + rng() * 3.5) * scale, (1.8 + rng() * 1.2) * scale, 0, 0, Math.PI * 2);
    ctx.fill();
    ctx.restore();
  }
  ctx.restore();
}

function renderWindCraft() {
  document.getElementById("wcWindVal").textContent = document.getElementById("wcWind").value + "%";
  document.getElementById("wcSeedsVal").textContent = document.getElementById("wcSeeds").value;

  const canvas = document.getElementById("windCanvas");
  const ctx = canvas.getContext("2d");
  drawWindArtwork(ctx, canvas.width, canvas.height);

  if (document.getElementById("wcShowGuide").checked) {
    drawEditorialGuideOnCanvas(ctx, canvas.width, canvas.height, document.getElementById("wcPalette").value === "morning");
  }
}

function drawEditorialGuideOnCanvas(ctx, cw, ch, useDarkText) {
  ctx.save();
  ctx.strokeStyle = useDarkText ? "rgba(40,35,30,0.65)" : "rgba(255,255,255,0.82)";
  ctx.lineWidth = 3;
  ctx.setLineDash([16, 12]);
  ctx.beginPath();
  ctx.moveTo(cw / 2, 0);
  ctx.lineTo(cw / 2, ch);
  ctx.stroke();

  ctx.setLineDash([8, 6]);
  ctx.strokeStyle = "rgba(230, 75, 55, 0.85)";
  const tx = cw * 0.585, ty = ch * 0.11, tw = cw * 0.325, th = ch * 0.17;
  ctx.strokeRect(tx, ty, tw, th);

  ctx.fillStyle = useDarkText ? "rgba(35,30,25,0.9)" : "rgba(255,255,255,0.94)";
  ctx.font = "92px 'Hiragino Mincho ProN', serif";
  ctx.textAlign = "center";
  ctx.fillText("こめびと", tx + tw / 2, ty + th * 0.78);

  const ex = cw * 0.875, ey = ch * 0.31, ew = cw * 0.085, eh = ch * 0.31;
  ctx.strokeRect(ex, ey, ew, eh);
  ctx.font = "bold 20px sans-serif";
  ctx.fillText("エッセイ帯", ex + ew / 2, ey + eh / 2);
  ctx.restore();
}

